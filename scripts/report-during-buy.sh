#!/usr/bin/env bash
# Концерт 7: продано 120 мест из 200. Организатор открывает отчёт,
# а между двумя его запросами Аня покупает место 14.
# На этом теге покупка — три запроса в Serializable, и с паузой Demo__PauseMs
# (500 мс после каждого запроса) она фиксируется примерно через 1,5 с после старта.
# Поэтому покупка стартует первой, а отчёт — через 1,2 с: его два запроса
# (около 1,2 и 1,7 с) встают по обе стороны от фиксации.
source "$(dirname "$0")/common.sh"

reset_seats
sql "UPDATE seats SET sold_to = '+7999' || lpad(id::text, 7, '0') WHERE id BETWEEN 81 AND 200;"
buy 7 14 "$ANYA" "Аня" &
sleep 1.2
report 7 "Отчёт посреди покупки"
wait
report 7 "Следующий отчёт"
